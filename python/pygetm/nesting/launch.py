"""
Launch commands for a nested run: one MPMD component per model, used by
pygetm-config (``pygetm-config nest``) and pygetm-nesting (``nesting-balance``).

Each model has its own run script (``<models>/<level>/run.py``) and becomes one
component of the launch. pyGETM's ``split_mpmd`` finds the components from MPI's
``APPNUM`` (``mpiexec ... : ...``) or, with a single application (Slurm's
``srun --multi-prog``), from the level names; either way the ranks of a model
are one contiguous block, in the order given here (parents first).

Pinning (``bind``) is optional and off by default. Ranks are then placed on
consecutive cores (``core``) or hardware threads (``hwthread``) in rank order,
so each model gets a contiguous block of cores and the models do not share
cores.

- ``mpiexec_command``: ``mpiexec [binding] -n 4 python a/run.py ARGS : -n 2 ...``
- ``srun_multiprog``: the ``--multi-prog`` configuration (``0-3 python a/run.py ARGS``)
- ``srun_command``: ``srun -n N [binding] --multi-prog FILE``
- ``slurm_job``: a complete ``sbatch`` script (writes the configuration itself)
"""

import shlex
from typing import Optional, Sequence, Tuple

#: binding flags per launcher; ranks fill cores in rank order
MPIEXEC_BIND = {
    "mpich": {"core": ["-bind-to", "core", "-map-by", "core"],
              "hwthread": ["-bind-to", "hwthread", "-map-by", "hwthread"]},
    "openmpi": {"core": ["--bind-to", "core", "--map-by", "core"],
                "hwthread": ["--bind-to", "hwthread", "--map-by", "hwthread"]},
}
SRUN_BIND = {"core": ["--cpu-bind=cores", "--distribution=block:block"],
             "hwthread": ["--cpu-bind=threads", "--distribution=block:block"]}
BIND_CHOICES = ("none", "core", "hwthread")


def _check(models: Sequence[Tuple[str, int]]):
    if not models:
        raise ValueError("no models")
    names = [n for n, _ in models]
    if len(set(names)) != len(names):
        raise ValueError(f"a model appears twice: {names}")
    for name, n in models:
        if int(n) < 1:
            raise ValueError(f"model {name!r} has {n} ranks")


def program(name: str, script: str, args: str = "", python: str = "python") -> str:
    """The command of one model: ``python <script with {level}> <args with {level}>``."""
    cmd = f"{python} {shlex.quote(script.format(level=name))}"
    a = args.format(level=name).strip()
    return f"{cmd} {a}" if a else cmd


def mpiexec_command(models: Sequence[Tuple[str, int]], script: str, args: str = "", python: str = "python",
                    bind: str = "none", mpi: str = "mpich", mpiexec: str = "mpiexec",
                    multiline: bool = True) -> str:
    """MPMD ``mpiexec`` command line, one ``-n N`` component per (name, ranks)."""
    _check(models)
    head = [mpiexec] + ([] if bind == "none" else MPIEXEC_BIND[mpi][bind])
    parts = [f"-n {int(n)} {program(name, script, args, python)}" for name, n in models]
    if not multiline:
        return " ".join(head) + " " + " : ".join(parts)
    if len(head) > 1:  # binding flags on a line of their own
        return " \\\n".join([" ".join(head)] + [("    " if k == 0 else "  : ") + p for k, p in enumerate(parts)])
    lead = " " * (len(mpiexec) - 1)
    return " \\\n".join([f"{mpiexec} {parts[0]}"] + [f"{lead}: {p}" for p in parts[1:]])


def srun_multiprog(models: Sequence[Tuple[str, int]], script: str, args: str = "", python: str = "python") -> str:
    """Slurm ``--multi-prog`` configuration: one line per model, ranks in blocks."""
    _check(models)
    lines, r = [], 0
    for name, n in models:
        n = int(n)
        ranks = str(r) if n == 1 else f"{r}-{r + n - 1}"
        lines.append(f"{ranks:9s} {program(name, script, args, python)}")
        r += n
    return "\n".join(lines) + "\n"


def srun_command(models: Sequence[Tuple[str, int]], conf: str, bind: str = "none", srun: str = "srun") -> str:
    _check(models)
    n = sum(int(k) for _, k in models)
    return " ".join([srun, "-n", str(n)] + ([] if bind == "none" else SRUN_BIND[bind])
                    + ["--multi-prog", shlex.quote(conf)])


def slurm_job(models: Sequence[Tuple[str, int]], script: str, args: str = "", python: str = "python",
              bind: str = "none", job_name: str = "nesting", partition: Optional[str] = None,
              time: Optional[str] = None, nodes: Optional[int] = None, account: Optional[str] = None,
              setup: Sequence[str] = (),
              comments: Sequence[str] = ("generated by nesting-balance (pygetm.nesting.launch)",)) -> str:
    """An ``sbatch`` script for the nested run: allocates all ranks, writes the
    ``--multi-prog`` configuration next to the job and starts it with srun.
    *setup* lines (environment, variables used in *args*) come before srun;
    *comments*: the lines of the header after the ranks per model (without ``#``)."""
    _check(models)
    n = sum(int(k) for _, k in models)
    opts = [f"--job-name={job_name}", f"--ntasks={n}", "--cpus-per-task=1"]
    if nodes:
        opts.append(f"--nodes={nodes}")
    if partition:
        opts.append(f"--partition={partition}")
    if time:
        opts.append(f"--time={time}")
    if account:
        opts.append(f"--account={account}")
    if bind == "core":
        opts.append("--hint=nomultithread")  # one rank per physical core
    opts.append("--output=%x-%j.out")
    summary = ", ".join(f"{name}={int(k)}" for name, k in models)
    conf = srun_multiprog(models, script, args, python)
    lines = ["#!/bin/bash"] + [f"#SBATCH {o}" for o in opts] + [
        f"# ranks per model: {summary}",
    ] + [f"# {c}" for c in comments] + [
        "",
        "set -eo pipefail",
    ] + list(setup) + [
        "",
        "conf=multiprog-${SLURM_JOB_ID}.conf",
        "# unquoted: shell variables in the arguments are expanded here, srun does not",
        "cat > \"$conf\" <<EOF",
        conf.rstrip("\n"),
        "EOF",
        srun_command(models, "$conf", bind).replace("'$conf'", "\"$conf\""),
        "",
    ]
    return "\n".join(lines)
